def read_sql(path, tmp_path):
    store = Store(tmp_path / (path.stem + "-read.sqlite"), Model())
    parse_sql(path, store)
    store.flush()
    result = {name: ([f["name"] for f in table["fields"]], list(store.rows(table["id"]))) for name, table in store.tables.items() if table["rows"]}
    store.close()
    return result


def test_all_exports_privacy_integrity_precision_and_sys_id(tmp_path):
    src = tmp_path / "source.sql"
    src.write_text(SQL, encoding="utf-8")
    output, project = tmp_path / "out", tmp_path / "client.snpanon"
    report = run(Options(src, output, project))
    assert report["rows"] == 6 and report["tables"] == 4
    assert report["validation"]["preserved_fields_equal"]
    texts = [p.read_text(encoding="utf-8") for p in output.rglob("*") if p.is_file()]
    for secret in ["SAME_KEY", "OTHER_KEY", "SECRET_", "client_secret", "11111111-1111-4111-8111-111111111111"]:
        assert all(secret not in text for text in texts)
    assert "1234567890.123456" in (output / "dump.sql").read_text(encoding="utf-8")
    assert "9876543210.123456" in (output / "inserts.sql").read_text(encoding="utf-8")
    parsed = read_sql(output / "dump.sql", tmp_path)
    schema = next(iter(parsed))[0]
    item_cols, item_rows = parsed[(schema, "item")]
    loc_cols, loc_rows = parsed[(schema, "loc")]
    sku_cols, sku_rows = parsed[(schema, "sku")]
    item = item_rows[0][item_cols.index("item")]
    loc = loc_rows[0][loc_cols.index("loc")]
    assert item.startswith("ITEM") and loc.startswith("LOC") and item != loc
    assert sku_rows[0][sku_cols.index("item")] == item
    assert sku_rows[0][sku_cols.index("loc")] == loc
    assert item_rows[0][item_cols.index("sys_id")] is None
    assert "GENERATED BY DEFAULT AS IDENTITY" in (output / "dump.sql").read_text(encoding="utf-8")
    assert '"sys_id"' not in (output / "inserts.sql").read_text(encoding="utf-8")
    assert item_rows[1][item_cols.index("proddescr")] is None
    assert item_rows[1][item_cols.index("note")] == ""
    with sqlite3.connect(project) as db:
        assert db.execute("SELECT count(*) FROM mapping WHERE old='SAME_KEY'").fetchone()[0] >= 2
    assert all(p.suffix not in {".sqlite", ".snpanon"} for p in output.rglob("*"))


