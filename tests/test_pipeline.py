def test_three_exports_have_identical_data(tmp_path):
    source = tmp_path / "source.sql"
    source.write_text(SQL, encoding="utf-8")
    output = tmp_path / "out"
    run(Options(source, output, tmp_path / "client.snpanon"))
    dump = read_sql(output / "dump.sql", tmp_path)
    manifest = json.loads((output / "csv/manifest.json").read_text())
    insert_store = Store(tmp_path / "inserts-typed.sqlite", Model())
    for entry in manifest["tables"]:
        insert_store.define((entry["schema"], entry["table"]), entry["fields"])
    parse_sql(output / "inserts.sql", insert_store)
    insert = {name: ([f["name"] for f in t["fields"]], list(insert_store.rows(t["id"]))) for name, t in insert_store.tables.items()}
    insert_store.close()
    csv_store = Store(tmp_path / "csv-read.sqlite", Model())
    parse_csv(output / "csv", csv_store)
    csv_data = {name: ([f["name"] for f in t["fields"]], list(csv_store.rows(t["id"]))) for name, t in csv_store.tables.items()}
    csv_store.close()
    for name, (columns, rows) in dump.items():
        kept = [i for i, col in enumerate(columns) if col != "sys_id"]
        normalized = ([columns[i] for i in kept], [[row[i] for i in kept] for row in rows])
        assert normalized == insert[name] == csv_data[name]


