"""Integration: full pipeline load into the local test PostgreSQL (anonymizer-es8).

Requires the scratch cluster from C:\pg-test (initdb -A trust, port 54329, db snp_test).
Tests skip automatically when the cluster is not running. Synthetic data only.
"""
import json
import os

import psycopg2
import pytest

from anonymizer.errors import AnonymizerError
from anonymizer.pipeline import Options, PgOptions, run

PG = dict(host=os.environ.get("SNP_PG_HOST", "localhost"), port=int(os.environ.get("SNP_PG_PORT", "54329")),
          dbname=os.environ.get("SNP_PG_DB", "snp_test"), user=os.environ.get("SNP_PG_USER", "postgres"))
SCHEMA = "public_77"


def cluster_available():
    try:
        psycopg2.connect(host=PG["host"], port=PG["port"], dbname=PG["dbname"], user=PG["user"], connect_timeout=2).close()
        return True
    except Exception:
        return False


def query(sql, params=()):
    connection = psycopg2.connect(host=PG["host"], port=PG["port"], dbname=PG["dbname"], user=PG["user"], connect_timeout=5)
    with connection, connection.cursor() as cursor:
        cursor.execute(sql, params)
        return cursor.fetchall()


def pg_options():
    return PgOptions(PG["host"], PG["port"], PG["dbname"], PG["user"], "", SCHEMA)


SOURCE = """
      CREATE TABLE public.parent(a text PRIMARY KEY, b numeric);
      CREATE TABLE public.child(x text REFERENCES public.parent(a), y numeric, note text);
      INSERT INTO public.parent VALUES ('SYN_A',1),('SYN_B',2);
      INSERT INTO public.child VALUES ('SYN_A',2.0,'SECRET_NOTE'),('SYN_B',1.0,'OTHER_NOTE');
    """


@pytest.fixture(scope="module")
def cluster():
    if not cluster_available():
        pytest.skip("локальный тестовый PostgreSQL не запущен (C:\\pg-test, порт 54329)")
    connection = psycopg2.connect(host=PG["host"], port=PG["port"], dbname=PG["dbname"], user=PG["user"])
    with connection, connection.cursor() as cursor:
        cursor.execute(f"DROP SCHEMA IF EXISTS {SCHEMA} CASCADE")
    connection.close()
    yield


def ensure_tables():
    """The target schema mirrors a deployed In.Plan: tables exist before the load.

    A customer would apply dump.sql DDL once; here the equivalent tables are
    created explicitly, including the sys_id identity that the loader never fills.
    """
    connection = psycopg2.connect(host=PG["host"], port=PG["port"], dbname=PG["dbname"], user=PG["user"])
    with connection, connection.cursor() as cursor:
        cursor.execute(f"CREATE SCHEMA IF NOT EXISTS {SCHEMA}")
        cursor.execute(f"""CREATE TABLE IF NOT EXISTS {SCHEMA}.parent(
            sys_id bigint GENERATED BY DEFAULT AS IDENTITY, a text PRIMARY KEY, b numeric)""")
        cursor.execute(f"""CREATE TABLE IF NOT EXISTS {SCHEMA}.child(
            sys_id bigint GENERATED BY DEFAULT AS IDENTITY, x text, y numeric, note text)""")
    connection.commit()
    connection.close()


def test_load_full_pipeline_into_schema(cluster, tmp_path):
    ensure_tables()
    src = tmp_path / "source.sql"
    src.write_text(SOURCE, encoding="utf-8")
    output = tmp_path / "out"
    report = run(Options(src, output, tmp_path / "synthetic.snpanon", pg=pg_options()))
    assert report["pg_load"] == {"schema": SCHEMA, "tables": 2, "rows": 4}
    assert output.is_dir()  # files published together with the successful load
    rows = query(f'SELECT a, b FROM {SCHEMA}.parent ORDER BY a')
    assert len(rows) == 2 and all("SYN" not in str(row) for row in rows)
    child = query(f"SELECT x, y, note, sys_id FROM {SCHEMA}.child ORDER BY x")
    assert child[0][2] != "SECRET_NOTE"
    assert all(row[3] is not None for row in child)  # identity generated, never our omitted sys_id
    assert query(f"SELECT 1 FROM information_schema.tables WHERE table_schema='{SCHEMA}' AND table_name='parent'")


def test_second_load_is_idempotent(cluster, tmp_path):
    ensure_tables()
    src = tmp_path / "source.sql"
    src.write_text(SOURCE, encoding="utf-8")
    run(Options(src, tmp_path / "one", tmp_path / "synthetic.snpanon", pg=pg_options()))
    run(Options(src, tmp_path / "two", tmp_path / "synthetic.snpanon", pg=pg_options()))
    (count,) = query(f"SELECT count(*) FROM {SCHEMA}.child")[0]
    assert count == 2  # truncate prevented doubling


def test_failure_mid_load_rolls_back_database_and_publishes_nothing(cluster, tmp_path):
    ensure_tables()
    src = tmp_path / "source.sql"
    src.write_text(SOURCE, encoding="utf-8")
    before = query(f"SELECT count(*) FROM {SCHEMA}.child")[0][0]
    # A CHECK the preserved measures violate makes COPY fail after TRUNCATE, mid-transaction.
    connection = psycopg2.connect(host=PG["host"], port=PG["port"], dbname=PG["dbname"], user=PG["user"])
    with connection, connection.cursor() as cursor:
        cursor.execute(f"ALTER TABLE {SCHEMA}.child DROP CONSTRAINT IF EXISTS guard_chk")
        # NOT VALID: existing rows are untouched; each COPY-inserted row is checked.
        cursor.execute(f"ALTER TABLE {SCHEMA}.child ADD CONSTRAINT guard_chk CHECK (y < 0) NOT VALID")
    connection.close()
    with pytest.raises(AnonymizerError, match="отменена"):
        run(Options(src, tmp_path / "out", tmp_path / "synthetic.snpanon", pg=pg_options()))
    assert not (tmp_path / "out").exists()
    assert query(f"SELECT count(*) FROM {SCHEMA}.child")[0][0] == before  # TRUNCATE rolled back
    connection = psycopg2.connect(host=PG["host"], port=PG["port"], dbname=PG["dbname"], user=PG["user"])
    with connection, connection.cursor() as cursor:
        cursor.execute(f"ALTER TABLE {SCHEMA}.child DROP CONSTRAINT guard_chk")
    connection.close()


def test_missing_target_table_blocks(cluster, tmp_path):
    ensure_tables()
    src = tmp_path / "source.sql"
    src.write_text(SOURCE, encoding="utf-8")
    connection = psycopg2.connect(host=PG["host"], port=PG["port"], dbname=PG["dbname"], user=PG["user"])
    with connection, connection.cursor() as cursor:
        cursor.execute(f"DROP TABLE {SCHEMA}.child")
    connection.close()
    with pytest.raises(AnonymizerError, match="нет таблиц датасета: child"):
        run(Options(src, tmp_path / "out", tmp_path / "synthetic.snpanon", pg=pg_options()))
    assert not (tmp_path / "out").exists()
    assert query(f"SELECT count(*) FROM {SCHEMA}.parent")[0][0] == 2  # untouched
