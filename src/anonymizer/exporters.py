from __future__ import annotations

import csv
import json
from pathlib import Path

from .metadata import quote


def copy_value(value):
    if value is None:
        return r"\N"
    return value.replace("\\", "\\\\").replace("\t", r"\t").replace("\n", r"\n").replace("\r", r"\r").replace("\b", r"\b").replace("\f", r"\f").replace("\v", r"\v")


def sql_value(value):
    if value is None:
        return "NULL"
    return "E'" + value.replace("\\", "\\\\").replace("'", "''").replace("\n", r"\n").replace("\r", r"\r").replace("\t", r"\t") + "'"


def csv_value(value):
    if value is None:
        return r"\N"
    # Escape leading backslash so a literal \N differs from SQL NULL.
    return "\\" + value if value.startswith("\\") else value


class Exporter:
    def __init__(self, directory, tables, schema_names):
        self.directory, self.tables, self.schema_names = directory, tables, schema_names
        (directory / "csv").mkdir()
        self.dump = (directory / "dump.sql").open("w", encoding="utf-8", newline="\n")
        self.inserts = (directory / "inserts.sql").open("w", encoding="utf-8", newline="\n")
        self.manifest = {"format": "snp-anonymizer-csv-v1", "encoding": "utf-8", "delimiter": ",", "null": r"\N", "leading_backslash": "doubled", "tables": []}
        self.dump.write("-- SNP Anonymizer: standalone table/data dump\nSET standard_conforming_strings = on;\nBEGIN;\n")
        self.inserts.write("-- SNP Anonymizer: data only; target tables must exist\nSET standard_conforming_strings = on;\nBEGIN;\n")
        for schema in schema_names.values():
            self.dump.write(f"CREATE SCHEMA IF NOT EXISTS {quote(schema)};\n")
        for name, table in tables.items():
            schema, tablename = schema_names[name[0]], name[1]
            full = f"{quote(schema)}.{quote(tablename)}"
            definitions = []
            for field in table["fields"]:
                if field["name"] == "sys_id":
                    definitions.append('"sys_id" bigint GENERATED BY DEFAULT AS IDENTITY')
                else:
                    definitions.append(f"{quote(field['name'])} {field['sql_type']}" + (" NOT NULL" if not field.get("nullable", True) else ""))
            self.dump.write(f"CREATE TABLE {full} (\n  " + ",\n  ".join(definitions) + "\n);\n")
        self.csv_stream = None

    def start(self, name, table):
        schema, table_name = self.schema_names[name[0]], name[1]
        self.full = f"{quote(schema)}.{quote(table_name)}"
        fields = [f for f in table["fields"] if f["name"] != "sys_id"]
        self.columns = ", ".join(quote(f["name"]) for f in fields)
        self.dump.write(f"COPY {self.full} ({self.columns}) FROM stdin;\n")
        sub = self.directory / "csv" / schema
        sub.mkdir(exist_ok=True)
        csv_path = sub / f"{table_name}.csv"
        self.csv_stream = csv_path.open("w", encoding="utf-8", newline="")
        self.csv_writer = csv.writer(self.csv_stream, lineterminator="\n")
        self.csv_writer.writerow([f["name"] for f in fields])
        self.manifest["tables"].append({"schema": schema, "table": table_name, "file": f"{schema}/{table_name}.csv", "rows": table["rows"],
                                        "fields": [{k: f[k] for k in ("name", "sql_type", "nullable")} for f in fields]})
        self.chunk, self.chunk_size = [], 0

    def row(self, row):
        self.dump.write("\t".join(copy_value(v) for v in row) + "\n")
        self.csv_writer.writerow([csv_value(v) for v in row])
        text = "(" + ",".join(sql_value(v) for v in row) + ")"
        self.chunk.append(text)
        self.chunk_size += len(text)
        if len(self.chunk) >= 500 or self.chunk_size >= 1024 * 1024:
            self.flush_inserts()

    def flush_inserts(self):
        if self.chunk:
            self.inserts.write(f"INSERT INTO {self.full} ({self.columns}) VALUES\n" + ",\n".join(self.chunk) + ";\n")
            self.chunk, self.chunk_size = [], 0

    def end(self):
        self.dump.write("\\.\n")
        self.flush_inserts()
        self.csv_stream.close()
        self.csv_stream = None

    def close(self, success):
        if success:
            self.dump.write("COMMIT;\n")
            self.inserts.write("COMMIT;\n")
            (self.directory / "csv/manifest.json").write_text(json.dumps(self.manifest, ensure_ascii=False, indent=2), encoding="utf-8")
        if self.csv_stream:
            self.csv_stream.close()
        self.dump.close()
        self.inserts.close()
