HELP_TEXT = """НАЗНАЧЕНИЕ

Приложение получает выгрузку данных In.Plan SNP (SQL-дамп; проверенный объём — около 1 ГиБ, XLSX-файл или папка CSV/XLSX) и готовит обезличенный набор: клиентские тексты и бизнес-коды заменяются на правдоподобные вымышленные, а количества, цены, даты и связи сохраняются. Установка и Python не требуются; файловый режим работает полностью offline.

КАК ПОЛЬЗОВАТЬСЯ

1. «Исходные данные»: «Файл…» — .sql, .xlsx или ZIP; «Папка…» — набор CSV/XLSX. ZIP содержит CSV/XLSX в корне либо одной подпапке или один SQL-дамп. Один XLSX-файл — одна таблица по имени файла, внутри ровно один лист; строка 1 — технические имена колонок. Повтор одной таблицы в разных файлах и сочетание XLSX с manifest.json запрещены.
2. «Папка результата» — обязательно НОВАЯ папка; существующие данные не перезаписываются.
3. «Локальный проект» — файл .snpanon с картой замен (см. ниже).
4. «Обезличить и экспортировать» — обработка идёт с прогрессом; «Отмена» останавливает её до начала фиксации PostgreSQL. После начала фиксации гарантировать откат нельзя (см. ниже).
Поле «Схемы SQL» ограничивает обработку выбранными схемами (пусто — все).
Во внешнем CSV без manifest.json пустая ячейка в необязательном числовом поле означает NULL, включая пустоту в кавычках. Пустой текст сохраняется; пробелы и непустые числа не меняются. Для NULL в датах используйте явный токен \\N. Для CSV с manifest.json NULL обозначается только токеном \\N.

ИМПОРТ XLSX

Скрытые и отфильтрованные строки читаются, полностью пустые строки пропускаются. Отсутствующая ячейка — NULL; явно пустой текст сохраняется, а в необязательном NUMBER/INTEGER означает NULL. Токен \\N также означает NULL. Формулы, включая сохранённый результат, Excel-ошибки, дополнительные листы и объединённые ячейки в области таблицы отклоняются.
Числа читаются без округления и float, формат отображения Excel не применяется: коды с ведущими нулями храните текстом. Округление, уже сделанное Excel, восстановить нельзя. Даты поддерживают ISO и системы Excel 1900/1904; фиктивное 29.02.1900 и потеря точности запрещены. Настройки кодировки и разделителя относятся только к CSV; --csv-schema действует и на XLSX. Старые .xls, .xlsb, .xlsm и защищённые книги не поддерживаются.

ОБРАБОТКА БЕЗ ЭТАЛОНА (НЕОБЯЗАТЕЛЬНО)

Галочка «Обрабатывать без эталонной модели» отключает правила эталона для всего входа, включая известные таблицы и дополнительные колонки. CLI: --bypass-model. Структура CSV/XLSX определяется автоматически по всем строкам; для SQL нужна входная DDL-структура.
Все обычные тексты заменяются; числа, включая числовые коды, булевы и даты сохраняются. sys_id очищается до NULL, update_date_time сохраняется как прочитано, change_author заменяется на snp. Системные поля не проверяются по значениям и ключам. Связи и ключи не определяются и не проверяются; замены независимы по колонкам. Несовместимые типы в колонке дают ошибку таблицы. Старые домены проекта не используются: повторение в этом режиме сохраняет свои замены. По умолчанию галочка выключена.
Новые текстовые подписи содержат имя колонки, например product_000001 и resource_000001; в коротких полях используется компактный код. Уже сохранённые замены остаются прежними: для перехода со старых «Атрибут 0001» создайте новый проект. Числа, UUID и обработка содержимого JSON от этого изменения не зависят.

ПРОЕКТ .SNPANON И ПОВТОРНЫЙ ЗАПУСК

Проект хранит соответствия «исходное значение и его замена». Повторная выгрузка того же клиента с тем же проектом даёт те же замены — наборы можно сравнивать между собой. Разным клиентам — разные проекты. Отрасль фиксируется за проектом и не меняется.
ВНИМАНИЕ: проект содержит ИСХОДНЫЕ значения. Храните его отдельно и никогда не передавайте вместе с обезличенным результатом.

КАРТА ЗАМЕН В EXCEL (НЕОБЯЗАТЕЛЬНО)

Поле «Карта замен в Excel» (или флаг --mapping-xlsx) записывает полную таблицу «что на что изменено»: домен, исходное значение, замена. Файл всегда создаётся ВНЕ папки результата и содержит исходные значения — храните его вместе с проектом и не передавайте получателям данных. Значения записываются текстом, включая строки с начальным знаком =. Ошибка подготовки Excel отменяет обработку до подключения к PostgreSQL, без публикации пакета. Очень длинные значения усекаются до 32 000 символов; при переполнении листа данные продолжаются на листах mapping_2, mapping_3…

ЧТО ЗАМЕНЯЕТСЯ И ЧТО СОХРАНЯЕТСЯ

Все новые текстовые замены — на ASCII-латинице, включая описания и заменяемые строки/ключи JSON: например Milk chocolate - series 0001, North site 0001, Attribute 0001. Сохраняемые исходные поля не транслитерируются. Если старый проект содержит нужную нелатинскую замену, создайте новый .snpanon: прежняя карта не переписывается. При экспорте Excel-карты проверяется также история замен.

• Заменяются: названия товаров, площадок, ресурсов, каналов, бренды, категории, адреса, комментарии и прочие клиентские тексты; бизнес-коды и числовые идентификаторы (согласованно по связям: одна сущность получает одно значение везде).
• Сохраняются точно: количества, цены, даты, булевы и флаги, стандартные единицы измерения, ABC/XYZ, числа и ISO-даты внутри JSON и структура JSON.
• Системные поля: sys_id выдаётся как NULL, update_date_time сохраняется без проверки значения, change_author всегда равен snp. В XLSX сохраняется прочитанное представление этих ячеек, включая числовые даты. Их PK/UK/FK не проверяются. В data-only inserts.sql и при загрузке в существующий PostgreSQL очищенный sys_id не передаётся, значение назначает целевая БД.

ПРОВЕРКИ (отчёт report.json)

Перед выдачей приложение сверяет исходный и обработанный наборы: число строк, сохраняемые поля и JSON, ссылочную целостность (составные внешние ключи проверяются целыми кортежами) и уникальность бизнес-ключей по каждой группе PK/UNIQUE. Исходные дефекты данных (например, битые ссылки) показываются в отчёте «до» и «после», но не исправляются. Если master-таблица не выгружена, связь помечается как непроверенная. Расхождение, внесённое обработкой, блокирует выдачу.

РЕЗУЛЬТАТ

• dump.sql — самостоятельный дамп PostgreSQL (схемы, таблицы, данные COPY);
• inserts.sql — только данные (INSERT), для существующих таблиц;
• csv/ — те же данные в UTF-8 CSV с manifest.json (структура и формат NULL);
• report.json — версии, правила полей, проверки и предупреждения.

ЗАГРУЗКА В POSTGRESQL (НЕОБЯЗАТЕЛЬНО)

Блок «3. Загрузка в PostgreSQL» включает выгрузку датасета в указанную вами базу после всех проверок. Укажите хост, порт, базу, пользователя, пароль и целевую схему (например, public_5). Таблицы датасета должны уже существовать в этой схеме — приложение загружает данные в готовую схему In.Plan и не создаёт таблицы. Данные заменяют содержимое только таблиц датасета (TRUNCATE без CASCADE + вставка) строго в одной PG-транзакции. Ошибка или отмена до начала фиксации откатывает весь набор, включая очистку, и убирает новый пакет. Excel, отчёт, проект и пакет публикуются до PG-фиксации. При поздней локальной ошибке дополнительные соответствия проекта или Excel-карта могут сохраниться; повторный запуск использует сохранённые замены.

Файлы и PostgreSQL не образуют общую транзакцию. При потере подтверждения фиксации исход загрузки неизвестен: пакет, проект и Excel-карта сохраняются для проверки целевых таблиц. После начала фиксации отмена не гарантирует откат. Поле pg_commit_status в отчёте: not_confirmed — подтверждение отсутствует, committed — фиксация подтверждена. Если после успешной загрузки обновить отчёт не удалось, приложение выдаёт предупреждение, а отчёт остаётся с not_confirmed. Пароль не сохраняется и не попадает в отчёт. Подключение идёт только к указанному вами серверу.

БЕЗОПАСНОСТЬ

• Входные данные читаются, но не исполняются: SQL-команды входа никогда не выполняются.
• Сеть используется только для опциональной загрузки в указанный вами PostgreSQL; файловый режим не выходит в сеть.
• Временные файлы удаляются после завершения или отмены; при неизвестном исходе PG-фиксации опубликованный пакет сохраняется для проверки.
• Сообщения об ошибках не содержат клиентских значений.

ЖУРНАЛ ПРОВЕРОК И ОШИБОК

Кнопка «Выгрузить журнал (CSV)» внизу окна (активна после завершения прогона — включая неудачный или отменённый) сохраняет полный журнал: стадии, результат каждой проверки FK и групп ключей со счётчиками «до / после», все ошибки, пропущенные колонки выгрузки. В журнале только технические имена и счётчики — значений клиентов нет. Файл выбираете вы; в пакет результата он не входит.

ПРОПУСКАТЬ ТАБЛИЦЫ С ОШИБКАМИ (НЕОБЯЗАТЕЛЬНО)

Галка в блоке «1» продолжает обработку при табличных ошибках входа: битая XLSX-книга, CSV-файл или INSERT/COPY-блок пропускается целиком. Пропущенные таблицы видны в отчёте (skipped_tables) и в журнале с причиной. Ошибка загрузки любой таблицы в PostgreSQL откатывает весь набор при любом положении галки. Ошибки замены значений и расхождения целостности остаются фатальными — это признаки неверной обезлички, а не дефект данных.

Горячая клавиша: F1 — открыть эту справку."""


def show_help(parent, version):
    theme = install(parent.winfo_toplevel())
    px = theme["px"]
    window = tk.Toplevel(parent)
    window.configure(background=ds.BG_CANVAS)
    window.title(f"Справка — SNP Anonymizer {version}")
    window.geometry("760x580")
    window.minsize(560, 380)
    window.transient(parent)
    frame = ttk.Frame(window, padding=px(ds.SPACE_L))
    frame.pack(fill="both", expand=True)
    text = tk.Text(frame, wrap="word", relief="flat", background=ds.BG_SURFACE, foreground=ds.TEXT_PRIMARY,
                   font=theme["fonts"]["body"], padx=px(ds.SPACE_M), pady=px(ds.SPACE_M), takefocus=0)
    scroll = ttk.Scrollbar(frame, orient="vertical", command=text.yview)
    text.configure(yscrollcommand=scroll.set)
    scroll.pack(side="right", fill="y")
    text.pack(side="left", fill="both", expand=True)
    text.insert("1.0", HELP_TEXT)
    text.configure(state="disabled")
    close = ttk.Button(window, text="Закрыть", command=window.destroy, style="Primary.TButton")
    close.pack(pady=(0, px(ds.SPACE_M)))
    window.bind("<Escape>", lambda event: window.destroy())
    window.bind("<F1>", lambda event: show_help(parent, version))
    return window
