"""User-facing help window; offline native Tkinter, no browser."""
from __future__ import annotations

import tkinter as tk
from tkinter import ttk

from . import ds_tokens as ds

HELP_TEXT = """НАЗНАЧЕНИЕ

Приложение получает выгрузку данных In.Plan SNP (SQL-дамп; проверенный объём — около 1 ГиБ, или папка CSV) и готовит обезличенный набор: клиентские тексты и бизнес-коды заменяются на правдоподобные вымышленные, а количества, цены, даты и связи сохраняются. Установка и Python не требуются; файловый режим работает полностью offline.

КАК ПОЛЬЗОВАТЬСЯ

1. «Исходные данные» — файл .sql (выгрузка pg_dump с COPY или INSERT), ZIP-архив (CSV-набор в корне или одной подпапке, либо один .sql) либо папка CSV (одна таблица в файле, имена колонок в заголовке).
2. «Папка результата» — обязательно НОВАЯ папка; существующие данные не перезаписываются.
3. «Локальный проект» — файл .snpanon с картой замен (см. ниже).
4. «Обезличить и экспортировать» — обработка идёт с прогрессом; «Отмена» в любой момент останавливает её без создания результата.
Поле «Схемы SQL» ограничивает обработку выбранными схемами (пусто — все).

ПРОЕКТ .SNPANON И ПОВТОРНЫЙ ЗАПУСК

Проект хранит соответствия «исходное значение → замена». Повторная выгрузка того же клиента с тем же проектом даёт те же замены — наборы можно сравнивать между собой. Разным клиентам — разные проекты. Отрасль фиксируется за проектом и не меняется.
ВНИМАНИЕ: проект содержит ИСХОДНЫЕ значения. Храните его отдельно и никогда не передавайте вместе с обезличенным результатом.

КАРТА ЗАМЕН В EXCEL (НЕОБЯЗАТЕЛЬНО)

Поле «Карта замен в Excel» (или флаг --mapping-xlsx) записывает полную таблицу «что на что изменено»: домен, исходное значение, замена. Файл всегда создаётся ВНЕ папки результата и содержит исходные значения — храните его вместе с проектом и не передавайте получателям данных. Ошибка записи отменяет всю обработку без публикации пакета. Очень длинные значения усекаются до 32 000 символов; при переполнении листа данные продолжаются на листах mapping_2, mapping_3…

ЧТО ЗАМЕНЯЕТСЯ И ЧТО СОХРАНЯЕТСЯ

• Заменяются: названия товаров, площадок, ресурсов, каналов, бренды, категории, адреса, комментарии и прочие клиентские тексты; бизнес-коды и числовые идентификаторы (согласованно по связям: одна сущность получает одно значение везде).
• Сохраняются точно: количества, цены, даты, булевы и флаги, стандартные единицы измерения, ABC/XYZ, числа и ISO-даты внутри JSON и структура JSON.
• sys_id не экспортируется ни в одном формате; в дампе это автогенерируемое поле.

ПРОВЕРКИ (отчёт report.json)

Перед выдачей приложение сверяет исходный и обработанный наборы: число строк, сохраняемые поля и JSON, ссылочную целостность (составные внешние ключи проверяются целыми кортежами) и уникальность бизнес-ключей по каждой группе PK/UNIQUE. Исходные дефекты данных (например, битые ссылки) показываются в отчёте «до» и «после», но не исправляются. Если master-таблица не выгружена, связь помечается как непроверенная. Расхождение, внесённое обработкой, блокирует выдачу.

РЕЗУЛЬТАТ

• dump.sql — самостоятельный дамп PostgreSQL (схемы, таблицы, данные COPY);
• inserts.sql — только данные (INSERT), для существующих таблиц;
• csv/ — те же данные в UTF-8 CSV с manifest.json (структура и формат NULL);
• report.json — версии, правила полей, проверки и предупреждения.

ЗАГРУЗКА В POSTGRESQL (НЕОБЯЗАТЕЛЬНО)

Блок «3. Загрузка в PostgreSQL» включает выгрузку датасета в указанную вами базу после всех проверок. Укажите хост, порт, базу, пользователя, пароль и целевую схему (например, public_5). Таблицы датасета должны уже существовать в этой схеме — приложение загружает данные в готовую схему In.Plan и не создаёт таблицы. Данные заменяют содержимое таблиц датасета (TRUNCATE + вставка) строго в одной транзакции: при любой ошибке база полностью откатывается, а пакет файлов не создаётся. Пароль не сохраняется и не попадает в отчёт. Подключение идёт только к указанному вами серверу.

БЕЗОПАСНОСТЬ

• Входные данные читаются, но не исполняются: SQL-команды входа никогда не выполняются.
• Сеть используется только для опциональной загрузки в указанный вами PostgreSQL; файловый режим не выходит в сеть.
• Временные файлы удаляются после завершения или отмены.
• Сообщения об ошибках не содержат клиентских значений.

ЖУРНАЛ ПРОВЕРОК И ОШИБОК

Кнопка «Выгрузить журнал (CSV)» внизу окна (активна после завершения прогона — включая неудачный или отменённый) сохраняет полный журнал: стадии, результат каждой проверки FK и групп ключей со счётчиками «до→после», все ошибки, пропущенные колонки выгрузки. В журнале только технические имена и счётчики — значений клиентов нет. Файл выбираете вы; в пакет результата он не входит.

Горячая клавиша: F1 — открыть эту справку."""


def show_help(parent, version):
    window = tk.Toplevel(parent)
    window.title(f"Справка — SNP Anonymizer {version}")
    window.geometry("760x580")
    window.minsize(560, 380)
    window.transient(parent)
    frame = ttk.Frame(window, padding=ds.SPACE_M)
    frame.pack(fill="both", expand=True)
    text = tk.Text(frame, wrap="word", relief="flat", background=ds.BG_SURFACE, foreground=ds.TEXT_PRIMARY,
                   font=(ds.FONT_FALLBACK, -14), padx=ds.SPACE_M, pady=10, takefocus=0)
    scroll = ttk.Scrollbar(frame, orient="vertical", command=text.yview)
    text.configure(yscrollcommand=scroll.set)
    scroll.pack(side="right", fill="y")
    text.pack(side="left", fill="both", expand=True)
    text.insert("1.0", HELP_TEXT)
    text.configure(state="disabled")
    close = ttk.Button(window, text="Закрыть", command=window.destroy, style="Primary.TButton")
    close.pack(pady=(0, ds.SPACE_M))
    window.bind("<Escape>", lambda event: window.destroy())
    window.bind("<F1>", lambda event: show_help(parent, version))
    return window
